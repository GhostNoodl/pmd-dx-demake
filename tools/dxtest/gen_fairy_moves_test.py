#!/usr/bin/env python3
"""Write tests/fairy_moves_dx.txt: the DX Fairy moves work. With all four known, A picks Moonblast against a
Dragon (Fairy is super effective, and it's the strongest) and it hits; Draining Kiss heals the user."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEADER = "***gDungeon+@gDxOffTeamPokemon+@gDxOffEntityInfo"
FOE = "**gDxTestStageMon+@gDxOffEntityInfo"
MOONBLAST, PLAY_ROUGH, DRAINING_KISS, DAZZLING_GLEAM, DRAGON, NORMAL = 0x16A, 0x169, 0x194, 0x19B, 0xF, 1


def stage(types):
    return [f"write gDxTestStageTypes 1 {types}", "write gDxTestStageTypes+1 1 0", "write gDxTestStageHP 2 0",
            "write gDxTestStageFoe 1 1", "write gDxTestStageFoe+1 1 0", "write gDxTestStageMate 1 0",
            "write gDxTestStageMate+1 1 0", "write gDxTestStage 1 1", "waitfor gDxTestStage 1 == 0 900", "wait 10"]


def moves(ids):
    out = []
    for i in range(4):
        mid = ids[i] if i < len(ids) else 0
        out += [f"write {LEADER}+@gDxOffInfoMoves!{8 * i} 1 {1 if mid else 0}", f"write {LEADER}+@gDxOffInfoMoves!{8 * i + 1} 1 0"]
        if mid:
            out += [f"write {LEADER}+@gDxOffInfoMoves!{8 * i + 2} 2 {mid}", f"write {LEADER}+@gDxOffInfoMoves!{8 * i + 4} 1 10"]
    return out


def main():
    out = ["#rom debug", "#save after-first-dungeon",
           "# DX Fairy moves (gen_dx_moves.py): A picks Moonblast against a Dragon and it hits; Draining Kiss heals.",
           "# Generated by tools/dxtest/gen_fairy_moves_test.py.",
           "mash START sMainMenu 4 != 0 3000",
           "wait 60", "press UP", "press A", "wait 30", "press A", "wait 30", "press UP", "press UP", "wait 10",
           "expect *sDxWarp+0xB0 4 == 2", "press A", "wait 40", "expect *sDxWarp+0xB0 4 == 1", "press A",
           "mash A gDungeon 4 != 0 1800", "wait 600",
           f"write {LEADER}+@gDxOffInfoTypes 1 0", f"write {LEADER}+@gDxOffInfoTypes!1 1 0",
           f"write {LEADER}+@gDxOffInfoHP 2 999"]
    out += ["# all four known; a Dragon next to the leader"] + moves([PLAY_ROUGH, DRAINING_KISS, DAZZLING_GLEAM, MOONBLAST]) + stage(DRAGON)
    out += [f"read hp0 {FOE}+@gDxOffInfoHP 2", "write gDxTestOut+8 2 99", "press A", "waitfor gDxTestOut+8 2 != 99 120",
            "wait 4", "shot 1_moonblast", f"expect gDxTestOut+8 2 == {MOONBLAST}", "wait 120",
            f"read hp1 {FOE}+@gDxOffInfoHP 2", "cmpreads hp1 < hp0", f"expect {LEADER}+@gDxOffInfoMoves!28 1 == 9", "wait 150"]
    out += ["# Draining Kiss alone, the leader hurt: it hits and heals the leader"] + moves([DRAINING_KISS]) + stage(NORMAL)
    out += [f"write {LEADER}+@gDxOffInfoMaxHP 2 999", f"write {LEADER}+@gDxOffInfoHP 2 100",
            f"read lhp0 {LEADER}+@gDxOffInfoHP 2", f"read fhp0 {FOE}+@gDxOffInfoHP 2",
            "write gDxTestOut+8 2 99", "press A", "waitfor gDxTestOut+8 2 != 99 120", "wait 4", "shot 2_draining_kiss",
            f"expect gDxTestOut+8 2 == {DRAINING_KISS}", "wait 120", f"read fhp1 {FOE}+@gDxOffInfoHP 2",
            f"read lhp1 {LEADER}+@gDxOffInfoHP 2", "cmpreads fhp1 < fhp0", "cmpreads lhp1 > lhp0", "shot 3_after"]
    (HERE / "tests/fairy_moves_dx.txt").write_text("\n".join(out) + "\n")
    print("wrote tests/fairy_moves_dx.txt")


if __name__ == "__main__":
    main()
