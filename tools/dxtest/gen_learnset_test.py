#!/usr/bin/env python3
"""Write tests/learnset_moves_dx.txt: Scenario S1's Lv. 20 recruits know the last four moves of their Gen 7
learnset (data/monster/dx/red_learnset, tools/dxtest/gen_dx_learnsets.py), not Red's."""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
# S1's team slots 2-5 (leader and partner keep the save's moves)
TEAM = [("Wailord", 346), ("Snorlax", 143), ("Pikachu", 25), ("Steelix", 233)]
LEVEL = 20


def last4(sets, name):
    e = next(x for x in sets if x["pokemon"] == name)
    known = []
    for m in e["levelUpMoves"]:
        if m["level"] > LEVEL:
            break
        if m["move"] not in known:
            known.append(m["move"])
            if len(known) > 4:
                known.pop(0)
    return known


def main():
    ids = {}
    for k, v in re.findall(r"#define (MOVE_\w+) (0x[0-9A-Fa-f]+|\d+)\b", (ROOT / "include/constants/move_id.h").read_text()):
        ids.setdefault(k, int(v, 0))
    dx = json.loads((ROOT / "data/monster/dx/red_learnset/learnset_data.json").read_text())
    red = json.loads((ROOT / "data/monster/learnset/learnset_data.json").read_text())
    sc = (HERE / "tests/scenarios_dx.txt").read_text()
    out = ["#rom debug", "#save after-first-dungeon",
           "# DX learnsets (Gen 7): Scenario S1's Lv. 20 recruits know the last four moves their Gen 7 learnset teaches",
           "# by then. Generated by tools/dxtest/gen_learnset_test.py.",
           sc[sc.index("# --- S1\n"):sc.index("# --- S2\n")].replace("reset\n", "", 1).strip()]
    for slot, (name, species) in enumerate(TEAM, 2):
        moves = last4(dx, name)
        out.append(f"# {name}: {', '.join(m[5:] for m in moves)} (Red's would be {', '.join(m[5:] for m in last4(red, name))})")
        base = f"***gDungeon+@gDxOffTeamPokemon!{4 * slot}+@gDxOffEntityInfo"
        out.append(f"expect {base}+@gDxOffInfoId 2 == {species}")
        out += [f"expect {base}+@gDxOffInfoMoves!{8 * j + 2} 2 == {ids[m]}" for j, m in enumerate(moves)]
    (HERE / "tests/learnset_moves_dx.txt").write_text("\n".join(out) + "\n")
    print("wrote tests/learnset_moves_dx.txt")


if __name__ == "__main__":
    main()
