#!/usr/bin/env python3
"""Write two behaviour tests on a staged fight (gDxTestStage, dx_rules.c):

tests/ai_no_regular_dx.txt: no Pokemon but the leader ever uses the regular attack (DX_NO_REGULAR_ATTACK);
  the AI keeps using moves, and a teammate out of PP next to a foe Struggles.
tests/exp_team_msg_dx.txt: a KO prints one "The team gained N Exp. Points!" line and no per-member
  Exp lines; a level-up still gets its own line."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEADER = "***gDungeon+@gDxOffTeamPokemon+@gDxOffEntityInfo"
PARTNER = "***gDungeon+@gDxOffTeamPokemon!4+@gDxOffEntityInfo"
FOE = "**gDxTestStageMon+@gDxOffEntityInfo"
PREAMBLE = ["mash START sMainMenu 4 != 0 3000",
            "wait 60", "press UP", "press A", "wait 30", "press A", "wait 30", "press UP", "press UP", "wait 10",
            "expect *sDxWarp+0xB0 4 == 2", "press A", "wait 40",
            "expect *sDxWarp+0xB0 4 == 1", "press A",
            "mash A gDungeon 4 != 0 1800", "wait 600",
            "expect *gDungeon+@gDxOffDungeonLocation 1 == 2",
            "expect *gDungeon+@gDxOffDungeonFloor 1 == 1"] + [f"write gDxTestCount+{2 * i} 2 0" for i in range(5)]


def stage(hp=0, mate=(0, 0)):
    return ["write gDxTestStageTypes 1 255", f"write gDxTestStageHP 2 {hp}",
            "write gDxTestStageFoe 1 1", "write gDxTestStageFoe+1 1 0",
            f"write gDxTestStageMate 1 {mate[0] & 0xFF}", f"write gDxTestStageMate+1 1 {mate[1] & 0xFF}",
            "write gDxTestStage 1 1", "waitfor gDxTestStage 1 == 0 900", "wait 10"]


def ai_test():
    out = ["#rom debug", "#save after-first-dungeon",
           "# DX: allies and foes never use the regular attack; they use moves, and Struggle once out of PP.",
           "# Generated by tools/dxtest/gen_ai_exp_tests.py."] + PREAMBLE
    out += [f"write {LEADER}+@gDxOffInfoMoves!2 2 154"]  # Tackle in slot 1
    # a foe next to the team that only knows Tackle uses it: the team takes damage
    out += [f"write {LEADER}+@gDxOffInfoMaxHP 2 999", f"write {PARTNER}+@gDxOffInfoMaxHP 2 999",
            f"write {LEADER}+@gDxOffInfoHP 2 999", f"write {PARTNER}+@gDxOffInfoHP 2 999"] + stage(mate=(0, 1))
    out += [f"write {FOE}+@gDxOffInfoMoves 1 5", f"write {FOE}+@gDxOffInfoMoves!2 2 154", f"write {FOE}+@gDxOffInfoMoves!4 1 20"]
    out += [f"write {FOE}+@gDxOffInfoMoves!{8 * i} 1 0" for i in (1, 2, 3)]
    for turn in range(3):
        out += stage(mate=(0, 1)) + ["write gDxTestOut+8 2 99", "press A", "wait 150"]
    out += [f"read lhp {LEADER}+@gDxOffInfoHP 2", f"read php {PARTNER}+@gDxOffInfoHP 2",
            "calc hp lhp + php", "calc full 999 + 999", "cmpreads hp < full", "shot 0_tackled"]
    for turn in range(16):
        out += [f"write {LEADER}+@gDxOffInfoHP 2 999", f"write {PARTNER}+@gDxOffInfoHP 2 999",
                f"write {LEADER}+@gDxOffInfoMoves!4 1 20"] + stage(mate=(0, 1)) + ["press A", "wait 150"]
        if turn == 3:
            out.append("shot 1_fight")
    out += ["shot 2_fight", "read regular_attacks gDxTestCount+4 2", "read ai_moves gDxTestCount+6 2",
            "expect gDxTestCount+4 2 == 0", "expect gDxTestCount+6 2 >= 8",
            "log --- the partner runs out of PP"]
    for turn in range(6):
        out += [f"write {LEADER}+@gDxOffInfoHP 2 999", f"write {PARTNER}+@gDxOffInfoHP 2 999",
                f"write {LEADER}+@gDxOffInfoMoves!4 1 20"]
        out += [f"write {PARTNER}+@gDxOffInfoMoves!{8 * i + 4} 1 0" for i in range(4)]
        out += stage(mate=(0, 1)) + ["press A", "wait 150"]
        if turn == 1:
            out.append("shot 3_struggle")
    out += ["read struggles gDxTestCount+8 2", "expect gDxTestCount+8 2 >= 1", "expect gDxTestCount+4 2 == 0"]
    (HERE / "tests/ai_no_regular_dx.txt").write_text("\n".join(out) + "\n")


def exp_test():
    out = ["#rom debug", "#save after-first-dungeon",
           "# DX: a KO gives one \"The team gained N Exp. Points!\" line, no per-member lines; level-ups keep theirs.",
           "# Generated by tools/dxtest/gen_ai_exp_tests.py."] + PREAMBLE
    out += [f"write {LEADER}+@gDxOffInfoMoves!2 2 154", f"write {LEADER}+@gDxOffInfoMoves!4 1 20",
            f"write {LEADER}+@gDxOffInfoHP 2 999",
            # this KO takes the Lv. 6 leader to Lv. 7 (a level-up keeps its own line)
            f"read leader_level {LEADER}+@gDxOffInfoLevel 1"]
    out += stage(hp=1) + ["shot 1_staged", "mash A gDxTestCount 2 >= 1 1500", "wait 40",
                          "shot 2_team_exp", "wait 120", "shot 3_level_up", "wait 400",
                          "expect gDxTestCount 2 == 1", "expect gDxTestCount+2 2 == 0",
                          f"read leader_level_after {LEADER}+@gDxOffInfoLevel 1",
                          "cmpreads leader_level_after > leader_level"]
    (HERE / "tests/exp_team_msg_dx.txt").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    ai_test()
    exp_test()
    print("wrote tests/ai_no_regular_dx.txt, tests/exp_team_msg_dx.txt")
