#!/usr/bin/env python3
"""Write tools/dxtest/tests/scenarios_dx.txt: every Scenarios entry (debug menu) loads and lands where it should.

Each scenario runs from a fresh power-on (the scratch save is never written)."""
from pathlib import Path

# scenario -> (dungeon id, floor) it warps to; None: it opens a screen instead
LANDS = {
    1: (0, 1), 2: (2, 2), 3: (5, 1), 4: (2, 1), 5: (0, 1), 6: (0, 1), 7: None, 8: (0, 1),
    9: (2, 1), 10: (2, 1), 11: (0, 1), 12: "map", 13: (1, 1), 14: (2, 9), 15: (33, 1),
}
MENU_DEBUG_UNKNOWN_1 = 52  # the Evolve tool (Luminous Cave)
MENU_DEBUG_SCENARIOS = 53


def digits(target, start):
    out = []
    if target // 10:
        out += ["press LEFT"] + ["press UP"] * (target // 10) + ["press RIGHT"]
    out += ["press UP"] * max(0, target % 10 - start % 10)
    out += ["press DOWN"] * max(0, start % 10 - target % 10)
    return out


def main():
    lines = ["#rom debug", "#save after-first-dungeon",
             "# Every Scenarios entry (Debug Mode -> Scenarios) sets up and lands where it should, without crashing.",
             "# Generated by tools/dxtest/gen_scenarios_test.py."]
    for n, lands in LANDS.items():
        lines += [f"# --- S{n}", "reset" if n > 1 else "# (power-on)",
                  "mash START sMainMenu 4 != 0 3000", "wait 60", "press UP", "press A", "wait 30"]
        lines += ["press DOWN"] * 7 + ["press A", "wait 30", f"expect *sMainMenu+4 4 == {MENU_DEBUG_SCENARIOS}"]
        lines += digits(n, 1) + ["wait 10", f"shot s{n:02d}_pick", "press A"]
        if lands is None:
            lines += ["wait 120", f"shot s{n:02d}_screen", f"expect *sMainMenu+4 4 == {MENU_DEBUG_UNKNOWN_1}"]
        elif lands == "map":
            lines += ["wait 900", f"shot s{n:02d}_world_map", "expect gDxScenario 1 == 12"]
        else:
            dungeon, floor = lands
            lines += ["mash A gDungeon 4 != 0 1800", "wait 600", f"shot s{n:02d}_in_dungeon",
                      f"expect gDxScenario 1 == {n}",
                      f"expect *gDungeon+@gDxOffDungeonLocation 1 == {dungeon}",
                      f"expect *gDungeon+@gDxOffDungeonFloor 1 == {floor}"]
    out = Path(__file__).resolve().parent / "tests/scenarios_dx.txt"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
