#!/bin/bash
# Generate tests/warp_<name>.txt: Debug Mode -> Warp -> list entry INDEX -> FLOOR,
# then check the dungeon id / floor in RAM.
#   gen_warp_test.sh NAME INDEX FLOOR DUNGEON_ID
# The digit widget starts at 0 (dungeon) / 1 (floor); LEFT selects the tens column.
set -euo pipefail
name=$1 index=$2 floor=$3 id=$4
out="$(dirname "$0")/tests/warp_$name.txt"

digits() { # $1 = target, $2 = start value
    local t=$1 s=$2 i
    if (( t / 10 > 0 )); then
        echo "press LEFT"
        for ((i = 0; i < t / 10; i++)); do echo "press UP"; done
        echo "press RIGHT"
    fi
    for ((i = s % 10; i < t % 10; i++)); do echo "press UP"; done
    for ((i = t % 10; i < s % 10; i++)); do echo "press DOWN"; done
}

{
    echo "#rom debug"
    echo "#save after-first-dungeon"
    echo "# generated by gen_warp_test.sh $*"
    echo "mash START sMainMenu 4 != 0 3000"
    echo "wait 60"
    echo "press UP"
    echo "press A"
    echo "wait 30"
    echo "press A"
    echo "wait 30"
    digits "$index" 0
    echo "wait 10"
    echo "expect *sDxWarp+0xB0 4 == $index"
    echo "shot 1_pick_dungeon"
    echo "press A"
    echo "wait 30"
    digits "$floor" 1
    echo "wait 10"
    echo "expect *sDxWarp+0xB0 4 == $floor"
    echo "shot 2_pick_floor"
    echo "press A"
    echo "mash A gDungeon 4 != 0 1800"
    echo "wait 600"
    echo "shot 3_in_dungeon"
    echo "expect *gDungeon+0x644 1 == $id"
    echo "expect *gDungeon+0x645 1 == $floor"
    echo "read floorCount *gDungeon+0x1D3D0 4"
    echo "hold RIGHT 40"
    echo "wait 60"
    echo "shot 4_moved"
} > "$out"
echo "wrote $out"
