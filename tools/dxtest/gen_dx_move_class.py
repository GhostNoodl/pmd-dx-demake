#!/usr/bin/env python3
"""Write src/data/dx_move_damaging.h: which of Red's moves deal damage (PokeAPI damage class physical/special).

Red's move data can't tell: status moves carry small base powers too (Growl has 2), so Smart A and Move
Growth need this list. Red-only moves (orbs, item throws) count as non-damaging, apart from the regular
attack. Cached in cache/pokeapi_moves.json."""
import json
import re
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
CACHE = HERE / "cache" / "pokeapi_moves.json"
URL = "https://beta.pokeapi.co/graphql/v1beta"
QUERY = "{ pokemon_v2_move { name pokemon_v2_movedamageclass { name } } }"
RENAMED = {"faintattack": "feintattack", "hijumpkick": "highjumpkick", "smellingsalt": "smellingsalts"}
ALWAYS = {"attack"}  # the regular attack


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def damage_classes():
    if not CACHE.exists():
        req = urllib.request.Request(URL, json.dumps({"query": QUERY}).encode(),
                                     {"Content-Type": "application/json", "User-Agent": "pmd-dx-demake-tools/1.0"})
        moves = json.loads(urllib.request.urlopen(req, timeout=120).read())["data"]["pokemon_v2_move"]
        CACHE.parent.mkdir(exist_ok=True)
        CACHE.write_text(json.dumps({m["name"]: (m["pokemon_v2_movedamageclass"] or {}).get("name") for m in moves}, indent=1))
    return {norm(k): v for k, v in json.loads(CACHE.read_text()).items()}


def main():
    classes = damage_classes()
    names = dict(re.findall(r'^(MoveName\w+):\n\.string "([^"\\]*)', (REPO / "data/move/move_names.s").read_text(), re.M))
    data = json.loads((REPO / "data/move/move_data.json").read_text())
    damaging, unknown = [], []
    for move_id, m in enumerate(data):
        name = names.get(m["name"], "")
        key = RENAMED.get(norm(name), norm(name))
        if key in ALWAYS or classes.get(key) in ("physical", "special"):
            damaging.append(move_id)
        elif key not in classes and m["basePower"] > 0:
            unknown.append(name)
    # the DX Fairy moves (tools/dxtest/gen_dx_moves.py) all deal damage
    consts = {k: int(v, 0) for k, v in re.findall(r"#define (MOVE_\w+) (0x[0-9A-Fa-f]+|\d+)\b",
                                                   (REPO / "include/constants/move_id.h").read_text())}
    for k in ("FAIRY_WIND", "DISARMING_VOICE", "DRAINING_KISS", "DAZZLING_GLEAM", "PLAY_ROUGH", "MOONBLAST"):
        damaging.append(consts["MOVE_" + k])
    bits = [0] * ((len(data) + 7) // 8)
    for i in damaging:
        bits[i // 8] |= 1 << (i % 8)
    rows = ",\n".join("    " + ", ".join(f"0x{b:02X}" for b in bits[i:i + 12]) for i in range(0, len(bits), 12))
    (REPO / "src/data/dx_move_damaging.h").write_text(
        "// Generated by tools/dxtest/gen_dx_move_class.py: bit set = the move deals damage (PokeAPI damage class)\n"
        f"static const u8 sDxMoveDamaging[{len(bits)}] = {{\n{rows}\n}};\n")
    print(f"{len(damaging)} damaging of {len(data)}; not in PokeAPI (counted non-damaging): {', '.join(unknown)}")


if __name__ == "__main__":
    main()
