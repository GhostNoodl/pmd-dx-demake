#!/usr/bin/env python3
"""Generate Rescue Team DX floor counts for modern builds (DX_FLOORS).

DX totals (Serebii's Rescue Team DX dungeon list, cross-checked with the Mystery
Dungeon Wiki "Differences From the Original Game" page) count peak/pit/grotto
sections together with the main dungeon. Where DX only changes a total, the
main section absorbs the change and the boss section is kept as-is.

For each resized dungeon this writes data/dungeon/<Dir>/dx/floor_id.json (same
label, picked by data/dungeon/floor_id.inc under DX_FLOORS) and
src/data/dx_floors.h (floor counts, mission difficulty, no-mission floors).

New floor i takes its layout/spawn/item tables from an original floor:
floor 1 stays floor 1, the original last (boss) floor stays last, floors in
between are spread evenly, and "special" floors (bosses/events from the
no-mission list in dungeon_info.c) are each kept exactly once.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# enum suffix: (data dir, DX floor count)
RESIZE = {
    "MT_THUNDER": ("MtThunder", 9),        # DX Mt. Thunder 12F total = 9 + Peak 3   (Red 10 + 3)
    "MT_BLAZE": ("MtBlaze", 11),           # DX 14F = 11 + Peak 3                    (Red 12 + 3)
    "FROSTY_FOREST": ("FrostyForest", 8),  # DX 13F = 8 + Grotto 5                   (Red 9 + 5)
    "MAGMA_CAVERN": ("MagmaCavern", 20),   # DX 23F = 20 + Pit 3                     (Red 23 + 3)
    "UPROAR_FOREST": ("UproarForest", 4),  # DX B4F                                  (Red B10F)
    "WESTERN_CAVE": ("WesternCave", 20),   # DX B20F                                 (Red B99F)
    "MT_FARAWAY": ("MtFaraway", 60),       # DX 60F                                  (Red 40F)
    "ODDITY_CAVE": ("OddityCave", 8),      # DX B8F                                  (Red B15F)
    "REMAINS_ISLAND": ("RemainsIsland", 13),  # DX B13F                              (Red B20F)
    "MARVELOUS_SEA": ("MarvelousSea", 18), # DX B18F                                 (Red B20F)
    "FANTASY_STRAIT": ("FantasyStrait", 25),  # DX B25F                              (Red B30F)
}

def camel(enum):
    return "".join(w.capitalize() for w in enum.split("_"))

def floor_map(old, new, specials):
    """Return src[i] (1-based original floor) for new floors 1..new."""
    if new == 1:
        return [old]
    src = [1 + round((i - 1) * (old - 1) / (new - 1)) for i in range(1, new + 1)]
    src[-1] = old
    # specials appear exactly once: snap the nearest sampled floor onto each one
    for sp in sorted(specials):
        if sp == old or sp in src:
            continue
        j = min(range(1, new - 1), key=lambda k: abs(src[k] - sp))
        src[j] = sp
    # duplicates of a special floor (when stretching) borrow a neighbour instead
    seen = set()
    for i, s in enumerate(src):
        if s in specials and s in seen:
            src[i] = s - 1 if s > 1 else s + 1
        seen.add(s)
    return src

def main():
    info = (ROOT / "src/dungeon_info.c").read_text()

    # no-mission list
    m = re.search(r"static const DungeonLocation gUnknown_8107828\[\] =\s*\{(.*?)\n\};", info, re.S)
    entries = re.findall(r"\{ \.id = DUNGEON_([A-Z0-9_]+), \.floor = (\d+) \}", m.group(1))
    specials = {}
    for d, f in entries:
        specials.setdefault(d, set()).add(int(f))

    counts = dict((d, int(n) - 1) for d, n in re.findall(r"\[DUNGEON_([A-Z0-9_]+)\]\s*=\s*(\d+),", info.split("sDungeonStartingFloor")[0]))

    out = ["// Generated by tools/dxtest/gen_dx_floors.py. Rescue Team DX floor counts.", ""]
    count_lines, diff_ptr_lines, maps = [], [], {}

    for enum, (ddir, new) in RESIZE.items():
        old = counts[enum]
        tables = json.loads((ROOT / f"data/dungeon/{ddir}/floor_id.json").read_text())
        assert len(tables["tables"]) == old, (enum, len(tables["tables"]), old)
        src = floor_map(old, new, specials.get(enum, set()))
        maps[enum] = src
        dx = {"name": tables["name"], "tables": [tables["tables"][s - 1] for s in src]}
        dx_dir = ROOT / f"data/dungeon/{ddir}/dx"
        dx_dir.mkdir(exist_ok=True)
        (dx_dir / "floor_id.json").write_text(json.dumps(dx, indent=4) + "\n")

        count_lines.append(f"    [DUNGEON_{enum}] = {new + 1}, /* was {old + 1} */")

        # mission difficulty, resampled with the same floor map
        dm = re.search(r"static const u8 sFloorMissionDifficulty_%s\[\] = \{(.*?)\};" % camel(enum), info, re.S)
        per = {}
        for a, b, v in re.findall(r"\[(\d+)(?: \.\.\. (\d+))?\] = (\d+)", dm.group(1)):
            for f in range(int(a), int(b or a) + 1):
                per[f] = int(v)
        out.append(f"static const u8 sFloorMissionDifficulty_{camel(enum)}_DX[] = {{")
        out.append("    [0] = 0,")
        for i, s in enumerate(src, 1):
            out.append(f"    [{i}] = {per[s]},")
        out.append("};")
        diff_ptr_lines.append(f"    [DUNGEON_{enum}] = sFloorMissionDifficulty_{camel(enum)}_DX,")

    # no-mission list with remapped floors
    out.append("")
    out.append("static const DungeonLocation gUnknown_8107828[] =")
    out.append("{")
    for d, f in entries:
        f = int(f)
        if d in maps:
            f = maps[d].index(f) + 1
        out.append(f"    {{ .id = DUNGEON_{d}, .floor = {f} }},")
    out.append("};")

    out.append("")
    out.append("#define DX_FLOOR_COUNT_OVERRIDES \\")
    out.append(" \\\n".join(count_lines))
    out.append("")
    out.append("#define DX_MISSION_DIFFICULTY_OVERRIDES \\")
    out.append(" \\\n".join(diff_ptr_lines))
    out.append("")
    (ROOT / "src/data/dx_floors.h").write_text("\n".join(out) + "\n")

    for enum, src in maps.items():
        print(f"{enum}: {counts[enum]} -> {len(src)} floors, from original floors {src}")

if __name__ == "__main__":
    sys.exit(main())
