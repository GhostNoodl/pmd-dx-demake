#!/usr/bin/env python3
"""Write tests/smart_a_dx.txt: what the A button picks, case by case (DX has no regular attack).

Each case sets the leader's four moves, stages one wild Pokemon of chosen types at a chosen spot
(gDxTestStage, dx_rules.c) and presses A once; the move Smart A chose is in gDxTestOut[4]
(-1 checked for traps, -2 talked)."""
from pathlib import Path

HERE = Path(__file__).resolve().parent

TACKLE, WATER_GUN, EMBER, GROWL, FLAMETHROWER, STRUGGLE = 0x9A, 0x134, 0x106, 0xD9, 0x35, 0x160
NORMAL, FIRE, WATER, GRASS, GHOST = 1, 2, 3, 4, 14
LEADER = "***gDungeon+@gDxOffTeamPokemon+@gDxOffEntityInfo"
FULL = [TACKLE, WATER_GUN, EMBER, GROWL]

# name, moves (None: empty slot), PP, foe types, foe offset, teammate offset, expected (op, value)
CASES = [
    ("fire_foe_water_gun", FULL, 20, (FIRE, 0), (1, 0), (0, 0), ("==", WATER_GUN)),
    ("grass_foe_ember", FULL, 20, (GRASS, 0), (1, 0), (0, 0), ("==", EMBER)),
    ("water_foe_tackle", FULL, 20, (WATER, 0), (1, 0), (0, 0), ("==", TACKLE)),
    ("ghost_foe_growl_not_tackle", [TACKLE, GROWL, None, None], 20, (GHOST, 0), (1, 0), (0, 0), ("==", GROWL)),
    ("far_foe_flamethrower", [TACKLE, GROWL, WATER_GUN, FLAMETHROWER], 20, (NORMAL, 0), (3, 0), (0, 0), ("==", FLAMETHROWER)),
    ("far_foe_no_growl", [TACKLE, GROWL, None, None], 20, (NORMAL, 0), (3, 0), (0, 0), ("<", 0)),
    ("facing_teammate_attacks", FULL, 20, (FIRE, 0), (1, 0), (0, 1), ("==", WATER_GUN)),
    ("no_pp_struggle", FULL, 0, (NORMAL, 0), (1, 0), (0, 0), ("==", STRUGGLE)),
    ("status_only_struggle", [GROWL, None, None, None], 20, (NORMAL, 0), (1, 0), (0, 0), ("==", STRUGGLE)),
]


def main():
    out = ["#rom debug", "#save after-first-dungeon",
           "# DX Smart A: the A button uses the best move that reaches a foe (power x type effectiveness x STAB),",
           "# status moves only when nothing else can hurt an adjacent foe, a move even when facing a teammate,",
           "# Struggle with no damaging move to use. Generated by tools/dxtest/gen_smart_a_test.py.",
           "mash START sMainMenu 4 != 0 3000",
           "wait 60", "press UP", "press A", "wait 30", "press A", "wait 30", "press UP", "press UP", "wait 10",
           "expect *sDxWarp+0xB0 4 == 2", "press A", "wait 40",
           "expect *sDxWarp+0xB0 4 == 1", "press A",
           "mash A gDungeon 4 != 0 1800", "wait 600",
           "expect *gDungeon+@gDxOffDungeonLocation 1 == 2",
           "expect *gDungeon+@gDxOffDungeonFloor 1 == 1",
           # no STAB to muddle the scores: the leader is typeless for the test
           f"write {LEADER}+@gDxOffInfoTypes 1 0", f"write {LEADER}+@gDxOffInfoTypes!1 1 0"]
    for n, (name, moves, pp, types, foe, mate, (op, want)) in enumerate(CASES):
        tag = f"c{n}"
        out.append(f"log --- {tag} {name}")
        out.append(f"write {LEADER}+@gDxOffInfoHP 2 999")
        for i, mid in enumerate(moves):
            base = f"{LEADER}+@gDxOffInfoMoves!{8 * i}"
            out += [f"write {base} 1 {1 if mid else 0}", f"write {LEADER}+@gDxOffInfoMoves!{8 * i + 1} 1 0"]
            if mid:
                out += [f"write {LEADER}+@gDxOffInfoMoves!{8 * i + 2} 2 {mid}",
                        f"write {LEADER}+@gDxOffInfoMoves!{8 * i + 4} 1 {pp}"]
        out += [f"write gDxTestStageTypes 1 {types[0]}", f"write gDxTestStageTypes+1 1 {types[1]}",
                f"write gDxTestStageFoe 1 {foe[0] & 0xFF}", f"write gDxTestStageFoe+1 1 {foe[1] & 0xFF}",
                f"write gDxTestStageMate 1 {mate[0] & 0xFF}", f"write gDxTestStageMate+1 1 {mate[1] & 0xFF}",
                "write gDxTestStage 1 1", "waitfor gDxTestStage 1 == 0 900", "wait 20",
                f"read {tag}_foe_dx gDxTestOut+12 2", f"read {tag}_foe_dy gDxTestOut+14 2",
                f"shot {name}_1_staged"]
        if mate != (0, 0):
            # the leader faces the teammate (gDxTestOut[3]); A must still strike the foe, not talk
            out += ["expect gDxTestOut+6 2 >= 0", f"read {tag}_faced {LEADER}+@gDxOffInfoDirection 1",
                    f"read {tag}_mate gDxTestOut+6 2", f"cmpreads {tag}_faced == {tag}_mate"]
        out += [
                "write gDxTestOut+8 2 99", "press A", "waitfor gDxTestOut+8 2 != 99 120",
                f"expect gDxTestOut+8 2 {op} {want}", f"read {tag}_dir gDxTestOut+10 2", "wait 90",
                f"shot {name}_2_after"]
        if mate != (0, 0):
            out.append(f"cmpreads {tag}_dir != {tag}_mate")
        if op == "==" and want != STRUGGLE:
            # the move was really used: its PP went down
            slot = moves.index(want)
            out.append(f"expect {LEADER}+@gDxOffInfoMoves!{8 * slot + 4} 1 == {pp - 1}")
        if want == STRUGGLE:
            out.append("expect gDxTestCount+8 2 >= 1")
        out.append("wait 200")
    (HERE / "tests/smart_a_dx.txt").write_text("\n".join(out) + "\n")
    print("wrote tests/smart_a_dx.txt")


if __name__ == "__main__":
    main()
