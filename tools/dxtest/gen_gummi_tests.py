#!/usr/bin/env python3
"""Write two Gummi tests (DX: Gummis are given at a Rescue Camp, never eaten in a dungeon).

tests/gummi_camp_dx.txt: the camp's Give Gummi menu (Red's camp Items -> Give; R in Debug -> Scenarios opens
  it for the leader) feeds a Rainbow Gummi, then a DX Gummi: each is used up, raises one stat by 1, and the
  DX Gummi always grants a Rare Quality.
tests/gummi_dungeon_dx.txt: Red's type Gummis turn into Rainbow Gummis (toolbox and storage) as an adventure
  starts; in the dungeon, Eat on a Gummi does nothing."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEADER = 42 * 88  # the after-first-dungeon save's leader, recruit slot 42
STATS = [f"*gRecruitedPokemonRef+{LEADER + 0x18 + i}" for i in range(4)]
QUALITY = f"*gRecruitedPokemonRef+{LEADER + 0x25}"
RAINBOW, DX_GUMMI, APPLE, RED_GUMMI, BLUE_GUMMI = 86, 239, 82, 87, 88


def toolbox(ids):
    out = []
    for i in range(20):
        out.append(f"write *gTeamInventoryRef+{4 * i} 1 0")
    for i, it in enumerate(ids):
        out += [f"write *gTeamInventoryRef+{4 * i} 1 1", f"write *gTeamInventoryRef+{4 * i + 2} 1 {it}"]
    return out


def stat_sum(name):
    out = [f"read {name}0 {STATS[0]} 1"]
    for i in range(1, 4):
        out += [f"read {name}_s{i} {STATS[i]} 1", f"calc {name}{i} {name}{i - 1} + {name}_s{i}"]
    return out


def to_scenarios():
    return ["mash START sMainMenu 4 != 0 3000", "wait 60", "press UP", "press A", "wait 30"] + \
        ["press DOWN"] * 7 + ["press A", "wait 30", "expect *sMainMenu+4 4 == 53", "wait 10"]


def give_first_gummi(tag):
    # R: the Give Gummi menu; the first toolbox item; Give; through the message until the menu closes
    return ["press R", "wait 40", f"shot {tag}_1_list", "press A", "wait 30", f"shot {tag}_2_give", "press A", "wait 60",
            f"shot {tag}_3_ate", "press A", "wait 60", f"shot {tag}_4_back"]


def camp():
    out = ["#rom debug", "#save after-first-dungeon",
           "# DX Gummis at a Rescue Camp: Give Gummi feeds a Rainbow Gummi, then a DX Gummi (a stat +1 each; the DX Gummi",
           "# always grants a Rare Quality). Generated by tools/dxtest/gen_gummi_tests.py."]
    out += to_scenarios()
    out += toolbox([RAINBOW, DX_GUMMI, APPLE]) + [f"write {QUALITY} 1 0"] + stat_sum("a")
    out += give_first_gummi("rainbow")
    out += ["# the Rainbow Gummi is gone (the DX Gummi moved up) and one stat rose by 1",
            "expect *gTeamInventoryRef+2 1 == -17", "expect *gTeamInventoryRef+6 1 == 82", "expect *gTeamInventoryRef+8 1 == 0"]
    out += stat_sum("b") + ["calc a4 a3 + 1", "cmpreads b3 == a4"]
    out += [f"write {QUALITY} 1 0"] + give_first_gummi("dx")[:-3] + ["press A", "wait 120", "shot dx_3b_quality"] + give_first_gummi("dx")[-3:]
    out += ["# the DX Gummi is gone, another stat +1, and a Rare Quality", "expect *gTeamInventoryRef+2 1 == 82",
            "expect *gTeamInventoryRef+4 1 == 0", f"expect {QUALITY} 1 != 0", f"read quality {QUALITY} 1"]
    out += stat_sum("c") + ["calc b4 b3 + 1", "cmpreads c3 == b4"]
    (HERE / "tests/gummi_camp_dx.txt").write_text("\n".join(out) + "\n")


def dungeon():
    storage = "*gTeamInventoryRef+{}".format(0x50 + 2 * RAINBOW)
    storage_blue = "*gTeamInventoryRef+{}".format(0x50 + 2 * BLUE_GUMMI)
    out = ["#rom debug", "#save after-first-dungeon",
           "# DX Gummis: Red's type Gummis turn into Rainbow Gummis as an adventure starts (toolbox and storage), and in",
           "# a dungeon Eat on a Gummi does nothing. Generated by tools/dxtest/gen_gummi_tests.py.",
           "mash START sMainMenu 4 != 0 3000"]
    out += toolbox([RAINBOW, RED_GUMMI]) + [f"write {storage} 2 2", f"write {storage_blue} 2 3"] + stat_sum("a")
    out += ["wait 60", "press UP", "press A", "wait 30", "press A", "wait 30", "press UP", "press UP", "wait 10",
            "expect *sDxWarp+0xB0 4 == 2", "press A", "wait 40", "expect *sDxWarp+0xB0 4 == 1", "press A",
            "mash A gDungeon 4 != 0 1800", "wait 600",
            "# the Red Gummi in the toolbox and the 3 Blue Gummis in storage are Rainbow Gummis now",
            "expect *gTeamInventoryRef+6 1 == 86", f"expect {storage} 2 == 5", f"expect {storage_blue} 2 == 0",
            "# Eat (the first choice) on the Rainbow Gummi: nothing happens",
            "press B", "wait 30", "press DOWN", "press A", "wait 40", "press A", "wait 40", "shot 1_gummi_menu",
            "press A", "wait 120", "shot 2_after_eat", "press B", "wait 20", "press B", "wait 20", "press B", "wait 40",
            "expect *gTeamInventoryRef+2 1 == 86", "expect *gTeamInventoryRef+6 1 == 86"]
    out += stat_sum("b") + ["cmpreads b3 == a3"]
    (HERE / "tests/gummi_dungeon_dx.txt").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    camp()
    dungeon()
    print("wrote tests/gummi_camp_dx.txt, tests/gummi_dungeon_dx.txt")
