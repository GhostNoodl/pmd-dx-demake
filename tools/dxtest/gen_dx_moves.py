#!/usr/bin/env python3
"""DX Fairy moves for modern builds (DX_RULES), in move ids Red never uses (include/constants/move_id.h).

Writes data/move/dx/move_data.json (Red's table with those six ids replaced; data/system_sbin.s includes it
instead of Red's) and data/move/dx/move_names_dx.s (their names and descriptions).

Power is on Red's scale (roughly a fifth of the mainline value); each copies a similar Red move's accuracy,
AI and range data. Their effects are in DxFairyMoveAction (dx_rules.c)."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# id constant, name, mainline power -> Red power, template move, range, PP, description
FAIRY = [
    ("MOVE_FAIRY_WIND", "Fairy Wind", 6, "MoveNameGust", "MOVE_RANGE_FRONT_FOE", 18,
     "Inflicts damage on the target."),
    ("MOVE_DISARMING_VOICE", "Disarming Voice", 6, "MoveNameSwift", "MOVE_RANGE_CUTS_CORNERS_FOE", 12,
     "Inflicts damage on the target.\\nIt never misses."),
    ("MOVE_DRAINING_KISS", "Draining Kiss", 9, "MoveNameGigaDrain", "MOVE_RANGE_FRONT_FOE", 10,
     "Inflicts damage on the target and\\nrestores the user's HP by part of\\nthe damage."),
    ("MOVE_DAZZLING_GLEAM", "Dazzling Gleam", 15, "MoveNameMistBall", "MOVE_RANGE_CUTS_CORNERS_FOE", 10,
     "Inflicts damage on the target with\\na brilliant light."),
    ("MOVE_PLAY_ROUGH", "Play Rough", 17, "MoveNameCrushClaw", "MOVE_RANGE_FRONT_FOE", 10,
     "Inflicts damage on the target.\\nIt may also lower the target's\\n{color YELLOW}Attack{reset}."),
    ("MOVE_MOONBLAST", "Moonblast", 18, "MoveNameCrushClaw", "MOVE_RANGE_FRONT_FOE", 10,
     "Inflicts damage on the target.\\nIt may also lower the target's\\n{color YELLOW}Sp. Atk{reset}."),
]


def main():
    consts = {k: int(v, 0) for k, v in re.findall(r"#define (MOVE_\w+) (0x[0-9A-Fa-f]+|\d+)\b",
                                                   (ROOT / "include/constants/move_id.h").read_text())}
    data = json.loads((ROOT / "data/move/move_data.json").read_text())
    by_name = {m["name"]: m for m in data}
    names = ["@ Generated by tools/dxtest/gen_dx_moves.py"]
    for const, display, power, template, rng, pp, desc in FAIRY:
        ident = re.sub(r"[^A-Za-z]", "", display)
        entry = dict(by_name[template])
        entry.update({"name": f"MoveName{ident}", "basePower": power, "type": "TYPE_FAIRY", "rangeID": rng,
                      "basePP": pp, "description": f"MoveDescription{ident}", "useText": "MoveUseTextUse"})
        if rng == "MOVE_RANGE_CUTS_CORNERS_FOE":
            entry["targetingFlags"] = entry["aiTargetingFlags"] = "0b0000000010000000"
        else:
            entry["targetingFlags"] = entry["aiTargetingFlags"] = "0b0000000000000000"
        data[consts[const]] = entry
        names += [f".global MoveName{ident}", f"MoveName{ident}:", f'.string "{display}\\0"', ".align 2,0",
                  f".global MoveDescription{ident}", f"MoveDescription{ident}:", f'.string "{desc}\\0"', ".align 2,0"]
    out = ROOT / "data/move/dx"
    out.mkdir(parents=True, exist_ok=True)
    (out / "move_data.json").write_text(json.dumps(data, indent=4) + "\n")
    (out / "move_names_dx.s").write_text("\n".join(names) + "\n")
    print("wrote data/move/dx/move_data.json, move_names_dx.s:", ", ".join(f[1] for f in FAIRY))


if __name__ == "__main__":
    main()
