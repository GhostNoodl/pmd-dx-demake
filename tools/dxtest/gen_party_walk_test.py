#!/usr/bin/env python3
"""Write tests/party6_walk_dx.txt: a party of 6 with three big Pokemon (Scenario S1) walks Tiny Woods for
three floors; all six must stay on the team and on the floor the whole way.

Regression test for a stack overflow in sub_8044574_Async (a 4-slot array filled for 6 team members),
which made the 6th member vanish on the next floor."""
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    random.seed(7)
    s = (HERE / "tests/scenarios_dx.txt").read_text()
    blk = s[s.index("# --- S1"):s.index("# --- S2")]
    blk = blk[:blk.index("expect gDxScenario")]
    out = ["#rom debug", "#save after-first-dungeon",
           "# Party of 6 (Scenario S1: Snorlax, Steelix, Wailord among them) walks three floors of Tiny Woods;",
           "# all six stay valid. Generated by tools/dxtest/gen_party_walk_test.py.", blk.strip()]

    def check(tag):
        r = []
        for i in range(6):
            r += [f"expect **gDungeon+@gDxOffTeamPokemon!{4 * i}+0 4 == 1",
                  f"read {tag}_x{i} **gDungeon+@gDxOffTeamPokemon!{4 * i}+@gDxOffEntityPos 2"]
        return r

    dirs = ["UP", "DOWN", "LEFT", "RIGHT"]
    for floor in (1, 2, 3):
        out.append("write ***gDungeon+@gDxOffTeamPokemon+@gDxOffEntityInfo+@gDxOffInfoHP 2 999")
        for k in range(8):
            out += ["press B", "wait 10", "press B", "wait 10"]
            out += [f"hold {random.choice(dirs)} {random.choice([40, 80, 120])}" for _ in range(4)]
            out += check(f"f{floor}w{k}")
        out.append(f"shot floor{floor}")
        if floor < 3:
            # the stairs: close any menu, end the floor, clear the flag on the next floor
            out += ["press B", "wait 20", "press B", "wait 20", "press B", "wait 20",
                    "write *gDungeon+@gDxOffFloorEnd 1 1",
                    f"mash A *gDungeon+@gDxOffDungeonFloor 1 == {floor + 1} 3000",
                    "write *gDungeon+@gDxOffFloorEnd 1 0", "wait 300"]
            out += check(f"f{floor + 1}start")
    (HERE / "tests/party6_walk_dx.txt").write_text("\n".join(out) + "\n")
    print("wrote tests/party6_walk_dx.txt")


if __name__ == "__main__":
    main()
