#!/usr/bin/env python3
"""Write tests/newcomer_attacks_dx.txt: every DX newcomer leads into Tiny Woods and attacks a staged foe
(Tackle via the A button); screenshots catch the attack animation, which must be the sprite's own (not
cropped: tools/spritecollab/sc_audit.py)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
LEADER = "***gDungeon+@gDxOffTeamPokemon+@gDxOffEntityInfo"


def species_ids():
    data = json.loads((ROOT / "data/monster/dx/monster_data.json").read_text())
    return {m["name"][len("MonsterName"):]: i for i, m in enumerate(data)}


def main():
    import sys
    sys.path.insert(0, str(HERE))
    import gen_dx_species
    ids = species_ids()
    out = ["#rom debug", "#save after-first-dungeon",
           "# Every DX newcomer leads into Tiny Woods and attacks a staged foe; shots catch the attack animation.",
           "# Generated by tools/dxtest/gen_newcomer_attack_test.py."]
    for n, s in enumerate(gen_dx_species.SPECIES):
        sid = ids[s["ident"]]
        if n:
            out.append("reset")
        out += [f"log --- {s['ident']} #{sid}", "mash START sMainMenu 4 != 0 3000",
                f"write *gRecruitedPokemonRef+3704 2 {sid}",
                "wait 60", "press UP", "press A", "wait 30", "press A", "wait 30", "press UP", "press UP", "wait 10",
                "expect *sDxWarp+0xB0 4 == 2", "press A", "wait 40", "expect *sDxWarp+0xB0 4 == 1", "press A",
                "mash A gDungeon 4 != 0 1800", "wait 600",
                f"expect {LEADER}+@gDxOffInfoId 2 == {sid}",
                f"write {LEADER}+@gDxOffInfoHP 2 999",
                f"write {LEADER}+@gDxOffInfoMoves 1 1", f"write {LEADER}+@gDxOffInfoMoves!2 2 154",
                f"write {LEADER}+@gDxOffInfoMoves!4 1 20",
                "write gDxTestStageTypes 1 255", "write gDxTestStageHP 2 0", "write gDxTestStageFoe 1 1",
                "write gDxTestStageFoe+1 1 0", "write gDxTestStageMate 1 0", "write gDxTestStageMate+1 1 0",
                "write gDxTestStage 1 1", "waitfor gDxTestStage 1 == 0 900", "wait 20",
                f"shot {s['ident'].lower()}_0_stand", "press A", "wait 6",
                f"shot {s['ident'].lower()}_1_attack", "wait 8", f"shot {s['ident'].lower()}_2_attack", "wait 8",
                f"shot {s['ident'].lower()}_3_attack",
                # it really attacked: Tackle's PP went down
                "wait 120", f"expect {LEADER}+@gDxOffInfoMoves!4 1 == 19"]
    (HERE / "tests/newcomer_attacks_dx.txt").write_text("\n".join(out) + "\n")
    print("wrote tests/newcomer_attacks_dx.txt")


if __name__ == "__main__":
    main()
