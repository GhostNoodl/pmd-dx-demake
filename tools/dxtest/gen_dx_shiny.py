#!/usr/bin/env python3
"""Shiny palettes for the Rescue Team DX shiny species (src/data/dx_shiny.h).

Red draws every Pokemon with one of 13 shared 16-colour palettes, and the GBA has no spare sprite
palette banks to give each shiny its own. So a shiny here is a palette swap: the shared palette
that best matches SpriteCollab's shiny colours.

For each species: SpriteCollab's normal and shiny Idle sheets give a normal->shiny colour map
(pixel by pixel). Each colour of the species' own Red palette is matched to its nearest normal
colour, mapped to shiny, and the Red palette closest to that shiny version (over the colour
indices the sprite actually uses) is chosen.
"""
import re
import sys
import urllib.error
import urllib.request
from collections import Counter, defaultdict
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
CACHE = Path.home() / "pmd/sc_shiny"
URL = "https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master/sprite/{path}/Idle-Anim.png"

# DX's shiny species: the 27 Strong Foes (src/data/dx_strong_foes.h) and Celebi (Mystery Houses)
SHINY = ["RAPIDASH", "AMPHAROS", "METAGROSS", "DRAGONITE", "AMBIPOM", "NOCTOWL", "AZUMARILL", "SPINDA",
         "LICKILICKY", "GYARADOS", "ESPEON", "SUDOWOODO", "SHUCKLE", "EXEGGCUTE", "WOBBUFFET", "BUTTERFREE",
         "AIPOM", "NINETALES", "ELECTRODE", "EXEGGUTOR", "STARMIE", "MAGIKARP", "DITTO", "HOOTHOOT",
         "CORSOLA", "ALTARIA", "ZANGOOSE", "CELEBI"]


def fetch(path, name):
    f = CACHE / name
    if not f.exists():
        try:
            data = urllib.request.urlopen(URL.format(path=path), timeout=60).read()
        except urllib.error.HTTPError:
            return None
        CACHE.mkdir(parents=True, exist_ok=True)
        f.write_bytes(data)
    return Image.open(f).convert("RGBA")


def read_pal(p):
    vals = [int(x) for x in p.read_text().split()[3:]]
    return [tuple(vals[i:i + 3]) for i in range(0, 48, 3)]


def dist(a, b):
    return sum((x - y) ** 2 for x, y in zip(a, b))


def main():
    import json
    consts = (ROOT / "include/constants/monster.h").read_text() + (ROOT / "include/constants/dx_species.h").read_text()
    ids = {k: int(v) for k, v in re.findall(r"#define MONSTER_(\w+) (\d+)\b", consts)}
    mons = json.loads((ROOT / "data/monster/dx/monster_data.json").read_text())
    pals = [read_pal(ROOT / f"graphics/ax/pal/{p}.pal") for p in range(13)]
    rows, log = [], []
    for name in SHINY:
        sid = ids[name]
        entry = mons[sid]
        dex = entry["dexInternal"][0]
        normal = fetch(f"{dex:04d}", f"{dex:04d}.png")
        shiny = fetch(f"{dex:04d}/0000/0001", f"{dex:04d}s.png")
        if normal is None or shiny is None or normal.size != shiny.size:
            log.append(f"{name}: no SpriteCollab shiny sprite, skipped")
            continue
        votes = defaultdict(Counter)
        for a, b in zip(normal.getdata(), shiny.getdata()):
            if a[3] and b[3]:
                votes[a[:3]][b[:3]] += 1
        cmap = {a: c.most_common(1)[0][0] for a, c in votes.items()}
        own = entry["overworldPalette"]
        # colour indices the Red sprite uses
        used = set()
        for png in (ROOT / "graphics/ax/mon" / entry["name"][11:].lower()).glob("*.png"):
            im = Image.open(png)
            if im.mode == "P":
                used.update(i for i in set(im.getdata()) if i)
        used = used or set(range(1, 16))
        target = {}
        for i in used:
            nearest = min(cmap, key=lambda c: dist(c, pals[own][i]))
            target[i] = cmap[nearest]
        best = min((p for p in range(13) if p != own), key=lambda p: sum(dist(pals[p][i], target[i]) for i in used))
        rows.append((name, best))
        log.append(f"{name}: palette {own} -> shiny {best}")
    hdr = "// Generated by tools/dxtest/gen_dx_shiny.py; don't edit by hand.\n"
    (ROOT / "src/data/dx_shiny.h").write_text(hdr + "// DX shiny species and the shared palette their shiny uses\n"
        + "static const struct DxShiny sDxShinies[] = {\n"
        + "".join(f"    {{ MONSTER_{n}, {p} }},\n" for n, p in rows) + "};\n")
    print("\n".join(log))


if __name__ == "__main__":
    main()
