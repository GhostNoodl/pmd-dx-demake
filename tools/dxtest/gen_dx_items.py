#!/usr/bin/env python3
"""Rescue Team DX item changes for modern builds (DX_RULES). Writes:

  data/item/dx/item_data.json             Red's item table with ITEM_G_MACHINE_6 (unused in Red)
                                          turned into the Evo Crystal
  data/item/dx/item_names_dx.s            its name and description
  data/dungeon/dx/dungeon_item_data.json  dungeon loot: evolution items are obsolete in DX, so
                                          their chance goes to Evo Crystals

Reusing an unused id keeps the item count, and with it Red's storage and save layout, unchanged.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CRYSTAL = "ITEM_G_MACHINE_6"
# items Red uses only to evolve (DX evolves with Evo Crystals instead)
EVOLUTION_ITEMS = {
    "ITEM_UPGRADE", "ITEM_KINGS_ROCK", "ITEM_THUNDERSTONE", "ITEM_DEEPSEASCALE", "ITEM_DEEPSEATOOTH",
    "ITEM_SUN_STONE", "ITEM_MOON_STONE", "ITEM_FIRE_STONE", "ITEM_WATER_STONE", "ITEM_METAL_COAT",
    "ITEM_LEAF_STONE", "ITEM_DRAGON_SCALE", "ITEM_LINK_CABLE", "ITEM_SUN_RIBBON", "ITEM_LUNAR_RIBBON",
    "ITEM_BEAUTY_SCARF",
}


def item_ids():
    return {k: int(v) for k, v in re.findall(r"#define (ITEM_\w+) (\d+)\b", (ROOT / "include/constants/item.h").read_text())}


def main():
    ids = item_ids()
    items = json.loads((ROOT / "data/item/item_data.json").read_text())
    fire = items[ids["ITEM_FIRE_STONE"]]
    crystal = items[ids[CRYSTAL]]
    crystal.update({
        "name": "ItemNameEvoCrystal", "buyPrice": 2500, "sellPrice": 250,
        "category": fire["category"], "spriteID": fire["spriteID"], "paletteID": 5,  # Red has item palettes 0-11
        "description": "ItemDescriptionEvoCrystal", "actionType": fire["actionType"],
        "order": fire["order"],
    })
    out = ROOT / "data/item/dx"
    out.mkdir(parents=True, exist_ok=True)
    (out / "item_data.json").write_text(json.dumps(items, indent=4) + "\n")
    (out / "item_names_dx.s").write_text("\n".join([
        "@ Generated by tools/dxtest/gen_dx_items.py",
        ".global ItemNameEvoCrystal", "ItemNameEvoCrystal:", '.string "Evo Crystal\\0"', ".align 2,0",
        ".global ItemDescriptionEvoCrystal", "ItemDescriptionEvoCrystal:",
        '.string "A crystal that holds the power of evolution.{NEW_LINE}'
        'Give it to a Pokémon at Luminous Cave to{NEW_LINE}evolve it. Some Pokémon need two.\\n\\0"',
        ".align 2,0", ""]))

    loot = json.loads((ROOT / "data/dungeon/dungeon_item_data.json").read_text())
    moved = 0
    for table in loot:
        for cat in table["categories"]:
            keep, gained = [], 0
            for it in cat["items"]:
                if it["item"] in EVOLUTION_ITEMS:
                    gained += it["itemProbability"]
                else:
                    keep.append(it)
            if gained:
                moved += 1
                existing = next((it for it in keep if it["item"] == CRYSTAL), None)
                if existing:
                    existing["itemProbability"] += gained
                else:
                    keep.append({"item": CRYSTAL, "itemProbability": gained})
                keep.sort(key=lambda it: ids.get(it["item"], 0))
                cat["items"] = keep
    dout = ROOT / "data/dungeon/dx"
    dout.mkdir(parents=True, exist_ok=True)
    (dout / "dungeon_item_data.json").write_text(json.dumps(loot, indent=4) + "\n")
    print(f"Evo Crystal = {CRYSTAL} (#{ids[CRYSTAL]}); {moved} loot categories now drop it instead of evolution items")


if __name__ == "__main__":
    main()
