#!/usr/bin/env python3
"""Import SpriteCollab portraits as Red kao files.

    sc_portrait.py OUT.inc SYMBOL DEX [--cache DIR]

Writes an assembler include defining `gKao<SYMBOL>`: a SIRO header pointing at Red's 13-slot
portrait table (Normal, Happy, Pained, Angry, Worried, Sad, Crying, Shouting, Teary-Eyed,
Determined, Joyous, Inspired, Surprised). Each portrait is 40x40 (5x5 tiles, 4bpp) with its own
16-colour palette, stored as AT4PX (literal-only stream: Red's decompressor accepts it, and it
saves writing a matcher). Emotions SpriteCollab lacks stay empty. Prints the dialogueSprites
bitmask (bit n = emotion n present) for monster_data.json.
"""
import argparse
import struct
import sys
import urllib.error
import urllib.request
from pathlib import Path

from PIL import Image

SC_URL = "https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master/portrait/{dex}/{name}.png"
# Red's portrait slots, by SpriteCollab emotion name
EMOTIONS = ["Normal", "Happy", "Pain", "Angry", "Worried", "Sad", "Crying", "Shouting",
            "Teary-Eyed", "Determined", "Joyous", "Inspired", "Surprised"]
SLOT_NAMES = ["Normal", "Happy", "Pained", "Angry", "Worried", "Sad", "Crying", "Shouting",
              "TearyEye", "Determined", "Joyous", "Inspired", "Surprised"]
SIZE = 40


def fetch(dex, name, cache):
    path = cache / f"{name}.png"
    missing = cache / f"{name}.missing"  # SpriteCollab has no such portrait (remembered, so offline runs work)
    if missing.exists():
        return None
    if not path.exists():
        try:
            data = urllib.request.urlopen(SC_URL.format(dex=dex, name=name), timeout=60).read()
        except urllib.error.HTTPError:
            cache.mkdir(parents=True, exist_ok=True)
            missing.touch()
            return None
        except urllib.error.URLError:
            if cache.is_dir() and any(cache.glob("*.png")):
                return None  # offline, and this species was fetched before: what is cached is all there is
            raise
        cache.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return Image.open(path).convert("RGB")


def to_4bpp(img):
    """16-colour palette (r, g, b) list and 5x5 tiles of 4bpp data, row-major."""
    if img.size != (SIZE, SIZE):
        sys.exit(f"portrait is {img.size}, expected {SIZE}x{SIZE}")
    # colour 0 of a BG palette is transparent and portraits are opaque, so 15 real colours
    colours = sorted(set(img.getdata()))
    if len(colours) > 15:
        img = img.quantize(15).convert("RGB")
        colours = sorted(set(img.getdata()))
    index = {c: i + 1 for i, c in enumerate(colours)}
    pal = [(0, 0, 0)] + colours + [(0, 0, 0)] * (15 - len(colours))
    px = img.load()
    out = bytearray()
    for ty in range(SIZE // 8):
        for tx in range(SIZE // 8):
            for y in range(8):
                for x in range(0, 8, 2):
                    lo = index[px[tx * 8 + x, ty * 8 + y]]
                    hi = index[px[tx * 8 + x + 1, ty * 8 + y]]
                    out.append(lo | (hi << 4))  # GBA 4bpp: low nibble is the left pixel
    return pal, bytes(out)


def at4px_literal(raw):
    """AT4PX container whose stream is all literals (flag byte 0xFF, then 8 bytes)."""
    body = bytearray()
    for i in range(0, len(raw), 8):
        chunk = raw[i:i + 8]
        body.append(0xFF)
        body += chunk
    header = b"AT4PX" + struct.pack("<H", 0x12 + len(body)) + bytes(9) + struct.pack("<H", len(raw))
    return header + bytes(body)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("symbol")
    ap.add_argument("dex")
    ap.add_argument("--cache", default=str(Path.home() / "pmd/spritecollab-portraits"))
    args = ap.parse_args()
    cache = Path(args.cache) / args.dex

    lines = [f"@ Generated by tools/spritecollab/sc_portrait.py from SpriteCollab portrait/{args.dex}",
             f".global gKao{args.symbol}", f"gKao{args.symbol}:", f"kao_siro sPortraits{args.symbol}"]
    table, mask = [], 0
    for slot, (emotion, label) in enumerate(zip(EMOTIONS, SLOT_NAMES)):
        img = fetch(args.dex, emotion, cache)
        if img is None:
            table.append("kao_portrait 0, 0")
            continue
        pal, raw = to_4bpp(img)
        gfx = at4px_literal(raw)
        mask |= 1 << slot
        name = f"s{args.symbol}{label}"
        lines += [f"{name}Pal:"] + [f".byte {r}, {g}, {b}, 0x80" for r, g, b in pal]
        lines += [f"{name}Gfx:"] + [".byte " + ", ".join(f"0x{b:02x}" for b in gfx[i:i + 16])
                                    for i in range(0, len(gfx), 16)]
        lines.append(".align 2, 0")
        table.append(f"kao_portrait {name}Pal, {name}Gfx")
    lines += [".align 2, 0", f"sPortraits{args.symbol}:"] + table
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"0b{mask:016b}")


if __name__ == "__main__":
    main()
