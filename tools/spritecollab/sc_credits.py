#!/usr/bin/env python3
"""Regenerate CREDITS.md from SpriteCollab's credit data.

Reads tools/spritecollab/imported.txt (one "<dex> <name> [sprite|portrait|both]" per line)
and, for each entry, SpriteCollab's sprite/<dex>/credits.txt and/or portrait/<dex>/credits.txt,
then resolves author IDs through credit_names.txt. SpriteCollab asks that every artist whose
work is used be credited; this keeps that list in sync with what we import.
"""
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = "https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master/"


def get(path):
    try:
        return urllib.request.urlopen(BASE + path, timeout=60).read().decode("utf-8")
    except urllib.error.HTTPError:
        return ""


def main():
    names = {}
    for line in get("credit_names.txt").splitlines()[1:]:
        cols = line.split("\t")
        if len(cols) >= 2:
            names[cols[1].strip()] = (cols[0].strip(), cols[2].strip() if len(cols) > 2 else "")
            names[cols[0].strip()] = names[cols[1].strip()]

    manifest = ROOT / "tools/spritecollab/imported.txt"
    entries = [l.split() for l in manifest.read_text().splitlines() if l.strip() and not l.startswith("#")]

    out = ["# Credits", "",
           "Sprites and portraits imported from [PMDCollab SpriteCollab](https://github.com/PMDCollab/SpriteCollab).",
           "Generated by `tools/spritecollab/sc_credits.py`; please don't edit by hand.", ""]
    for e in entries:
        dex, name = e[0], e[1]
        kinds = {"sprite": ["sprite"], "portrait": ["portrait"]}.get(e[2] if len(e) > 2 else "both", ["sprite", "portrait"])
        out.append(f"## {name} (#{dex})")
        for kind in kinds:
            authors = []
            for line in get(f"{kind}/{dex}/credits.txt").splitlines():
                cols = line.split("\t")
                if len(cols) >= 2:
                    who = cols[1].strip()
                    label, contact = names.get(who, (who, ""))
                    entry = f"{label}" + (f" ({contact})" if contact and not contact.startswith("<@") else "")
                    if entry not in authors:
                        authors.append(entry)
            out.append(f"- {kind.capitalize()}: " + (", ".join(authors) if authors else "(no credit data)"))
        out.append("")
    (ROOT / "CREDITS.md").write_text("\n".join(out))
    print(f"CREDITS.md: {len(entries)} species")


if __name__ == "__main__":
    main()
